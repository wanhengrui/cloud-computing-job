#!/usr/bin/env bash
# Turn env/node-inventory.env into the yaml the three CVMs consume. Doing this
# with a script (instead of editing three files by hand per machine) is what
# makes the "from blank host to running ring" part of the report reproducible.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${1:-$ROOT_DIR/env/node-inventory.env}"

if [ ! -f "$ENV_FILE" ]; then
  echo "missing inventory: $ENV_FILE" >&2
  echo "copy env/node-inventory.example.env to env/node-inventory.env first" >&2
  exit 2
fi

set -a
# shellcheck disable=SC1090
. "$ENV_FILE"
set +a

# A half-filled inventory silently produces a yaml that "looks fine" and then
# fails at run time with a routing error on the CVM. Catch it here instead.
for pair in "NODE_A ${NODE_A_HOST:-}" "NODE_B ${NODE_B_HOST:-}" "NODE_C ${NODE_C_HOST:-}"; do
  name="${pair%% *}"
  host="${pair#* }"
  case "$host" in
    "" | REPLACE* | 0.0.0.0 | *x.x.x*)
      echo "inventory incomplete: ${name}_HOST='$host' - fill the real private IP first" >&2
      exit 2
      ;;
  esac
done

OUT_DIR="$ROOT_DIR/config/cloud"
mkdir -p "$OUT_DIR"

# Cloud targets are private IP literals, so `direct` is the selector that works
# (1A proved `direct` cannot resolve container host names and `domain` is only
# needed when the target is a name).
node_yaml() {
  local letter="$1" name="$2" host="$3" port="$4" admin="$5"
  cat >"$OUT_DIR/dht-node-${letter}.yaml" <<EOF
# generated by scripts/gen-cloud-config.sh - do not edit by hand
global:
  threadmodel:
    default:
      - instance_name: default_instance
        io_handle_type: separate
        io_thread_num: 2
        handle_thread_num: 4

server:
  app: dht
  server: ${letter}
  admin_ip: 0.0.0.0
  admin_port: ${admin}
  service:
    - name: trpc.dht.${letter}.DhtService
      protocol: trpc
      network: tcp
      ip: 0.0.0.0
      port: ${port}

client:
  service:
    - name: trpc.dht.a.DhtService
      target: ${NODE_A_HOST}:${NODE_A_PORT}
      protocol: trpc
      network: tcp
      conn_type: long
      is_conn_complex: true
      selector_name: direct
    - name: trpc.dht.b.DhtService
      target: ${NODE_B_HOST}:${NODE_B_PORT}
      protocol: trpc
      network: tcp
      conn_type: long
      is_conn_complex: true
      selector_name: direct
    - name: trpc.dht.c.DhtService
      target: ${NODE_C_HOST}:${NODE_C_PORT}
      protocol: trpc
      network: tcp
      conn_type: long
      is_conn_complex: true
      selector_name: direct

plugins:
  log:
    default:
      - name: default
        sinks:
          local_file:
            filename: /tmp/dht-node-${letter}.log
EOF
}

node_yaml a node-a "$NODE_A_HOST" "$NODE_A_PORT" 19091
node_yaml b node-b "$NODE_B_HOST" "$NODE_B_PORT" 19092
node_yaml c node-c "$NODE_C_HOST" "$NODE_C_PORT" 19093

cat >"$OUT_DIR/dht-client.yaml" <<EOF
# generated by scripts/gen-cloud-config.sh
global:
  threadmodel:
    default:
      - instance_name: default_instance
        io_handle_type: merge
        io_thread_num: 2

client:
  service:
    - name: trpc.dht.a.DhtService
      target: ${NODE_A_HOST}:${NODE_A_PORT}
      protocol: trpc
      network: tcp
      conn_type: long
      is_conn_complex: true
      selector_name: direct
    - name: trpc.dht.b.DhtService
      target: ${NODE_B_HOST}:${NODE_B_PORT}
      protocol: trpc
      network: tcp
      conn_type: long
      is_conn_complex: true
      selector_name: direct
    - name: trpc.dht.c.DhtService
      target: ${NODE_C_HOST}:${NODE_C_PORT}
      protocol: trpc
      network: tcp
      conn_type: long
      is_conn_complex: true
      selector_name: direct
EOF

cat >"$OUT_DIR/trip-service.yaml" <<EOF
# generated by scripts/gen-cloud-config.sh
global:
  threadmodel:
    default:
      - instance_name: default_instance
        io_handle_type: separate
        io_thread_num: 2
        handle_thread_num: 4

server:
  app: ride
  server: trip
  admin_ip: 0.0.0.0
  admin_port: 18081
  service:
    - name: trpc.ride.trip.TripService
      protocol: trpc
      network: tcp
      ip: 0.0.0.0
      port: 8000

client:
  service:
    - name: trpc.ride.pricing.PricingService
      target: ${PRICING_HOST:-$NODE_B_HOST}:8000
      protocol: trpc
      network: tcp
      conn_type: long
      is_conn_complex: true
      selector_name: direct
    - name: trpc.dht.a.DhtService
      target: ${NODE_A_HOST}:${NODE_A_PORT}
      protocol: trpc
      network: tcp
      conn_type: long
      is_conn_complex: true
      selector_name: direct
    - name: trpc.dht.b.DhtService
      target: ${NODE_B_HOST}:${NODE_B_PORT}
      protocol: trpc
      network: tcp
      conn_type: long
      is_conn_complex: true
      selector_name: direct
    - name: trpc.dht.c.DhtService
      target: ${NODE_C_HOST}:${NODE_C_PORT}
      protocol: trpc
      network: tcp
      conn_type: long
      is_conn_complex: true
      selector_name: direct

plugins:
  log:
    default:
      - name: default
        sinks:
          local_file:
            filename: /tmp/trip-service.log
EOF

cat >"$OUT_DIR/ride-client.yaml" <<EOF
# generated by scripts/gen-cloud-config.sh
global:
  threadmodel:
    default:
      - instance_name: default_instance
        io_handle_type: merge
        io_thread_num: 2

client:
  service:
    - name: trpc.ride.trip.TripService
      target: ${TRIP_HOST:-$NODE_B_HOST}:8000
      protocol: trpc
      network: tcp
      conn_type: long
      is_conn_complex: true
      selector_name: direct
EOF

cat >"$OUT_DIR/node-inventory.env" <<EOF
# generated by scripts/gen-cloud-config.sh from $ENV_FILE
NODE_A_NAME=${NODE_A_NAME}
NODE_A_HOST=${NODE_A_HOST}
NODE_A_PORT=${NODE_A_PORT}
NODE_A_ID=${NODE_A_ID}
NODE_B_NAME=${NODE_B_NAME}
NODE_B_HOST=${NODE_B_HOST}
NODE_B_PORT=${NODE_B_PORT}
NODE_B_ID=${NODE_B_ID}
NODE_C_NAME=${NODE_C_NAME}
NODE_C_HOST=${NODE_C_HOST}
NODE_C_PORT=${NODE_C_PORT}
NODE_C_ID=${NODE_C_ID}
EOF

echo "generated in $OUT_DIR:"
ls -1 "$OUT_DIR"
echo
echo "ring (ascending node_id):"
printf '  %s id=%s %s:%s\n' "$NODE_A_NAME" "$NODE_A_ID" "$NODE_A_HOST" "$NODE_A_PORT"
printf '  %s id=%s %s:%s\n' "$NODE_B_NAME" "$NODE_B_ID" "$NODE_B_HOST" "$NODE_B_PORT"
printf '  %s id=%s %s:%s\n' "$NODE_C_NAME" "$NODE_C_ID" "$NODE_C_HOST" "$NODE_C_PORT"
